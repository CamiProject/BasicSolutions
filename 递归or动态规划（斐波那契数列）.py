# 普通递归，求第n项，直接递归

def fib(n):
    # 1. 终止条件：第 1 项和第 2 项的值都是 1
    if n == 1 or n == 2:
        return 1
    # 2. 递归拆解：当前项 = 前一项 + 前两项
    return fib(n - 1) + fib(n - 2)

print(fib(6))  # 输出：8

# 动态规划解决 重叠子问题

## 优化思路：“记忆化缓存+递归” （自顶向下的动态规划）

def fib(n, memo={}):
    # 1. 查表：如果之前已经算过 n 的结果，直接返回，不再重复计算
    if n in memo:
        return memo[n]
    
    # 2. 终止条件：如果 n 是 0 或 1，直接返回 n（fib(0)=0, fib(1)=1）
    if n <= 1:
        return n
    
    # 3. 递归计算：如果没有算过，才进行递归调用
    # 并将计算结果存入 memo 字典中，以便下次使用
    memo[n] = fib(n - 1, memo) + fib(n - 2, memo)
    
    # 4. 返回结果
    return memo[n]

## 思路2：表格法，（自底向上的动态规划）

def fib(n):
    # 1. 处理边界情况：如果是第 0 或 1 项，直接返回
    if n <= 1:
        return n
    
    # 2. 初始化“表格”（dp数组）
    # dp[i] 代表斐波那契数列的第 i 项
    # 这里初始化了前两项：dp[0]=0, dp[1]=1
    dp = [0, 1]
    
    # 3. 循环填表：从第 2 项开始，一直算到第 n 项
    # range(2, n + 1) 表示 i 会取 2, 3, ..., n
    for i in range(2, n + 1):
        # 状态转移方程：当前项 = 前一项 + 前两项
        # 将计算结果追加到 dp 列表的末尾
        dp.append(dp[i - 1] + dp[i - 2])
    
    # 4. 返回结果：dp[n] 就是我们要找的第 n 项
    return dp[n]
